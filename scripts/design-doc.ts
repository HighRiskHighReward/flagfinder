/** Generates docs/DESIGN.md from the design tokens, computing every text/background contrast pair. */
import { writeFileSync } from "node:fs";
import { contrastPairs, contrastRatio, scales, semantic } from "../apps/web/src/design/tokens";

const rows = (["light", "dark"] as const).flatMap((t) => contrastPairs.map((p) => {
  const r = contrastRatio(semantic[t][p.fg]!, semantic[t][p.bg]!);
  return `| ${t} | \`${p.fg}\` ${semantic[t][p.fg]} | \`${p.bg}\` ${semantic[t][p.bg]} | ${r.toFixed(2)}:1 | ${p.min}:1 | ${r >= p.min ? "pass" : "FAIL"} | ${p.use} |`;
}));
const scaleRows = Object.entries(scales).map(([n, s]) => `| ${n} | ${Object.entries(s).map(([k, v]) => `${k} \`${v}\``).join(" · ")} |`);
writeFileSync("docs/DESIGN.md", `# Design system

Generated by \`pnpm tsx scripts/design-doc.ts\` from \`apps/web/src/design/tokens.ts\`. The automated test
\`apps/web/test/unit/contrast.test.ts\` enforces every pair below.

## Brand anchors
Forest green \`#0B5D3B\` (green-700), deep black \`#090D0B\` (neutral-950), gold \`#D4AF37\` (gold-400), white \`#FFFFFF\`.
Scales were derived in OKLab around each anchor.

**Gold on white is ${contrastRatio("#D4AF37", "#FFFFFF").toFixed(2)}:1 — it fails WCAG AA for text.** In light mode gold is used only
for non-text accents (the "closing soon" badge background with black text, the active-pin ring, the mobile view-toggle bar).
Gold *text* in light mode uses the darker \`accent-text\` token (${semantic.light["accent-text"]}).

## Usage
- Green: primary actions (buttons, selected chips), links.
- Gold: selective emphasis — badges, focus ring in dark mode, active map pin, "closing soon".
- Black/white: structure. Decorative \`border\` is for cards and dividers only; inputs and controls use \`border-strong\` (≥3:1).
- Typography: Inter Variable (one variable font), minor-third scale (0.75–1.95 rem). Icons: lucide (one set).
- Touch targets ≥44×44 px (\`.tap\`), visible focus ring, \`prefers-reduced-motion\` disables transitions.
- Themes: system preference by default; manual override persisted in localStorage and applied by an inline
  script before first paint (no flash).

## Scales
| Scale | Steps |
|---|---|
${scaleRows.join("\n")}

## Text/background contrast (computed)
| Theme | Foreground | Background | Ratio | Required | Result | Used for |
|---|---|---|---|---|---|---|
${rows.join("\n")}
`);
console.log(`docs/DESIGN.md written (${rows.length} pairs, ${rows.filter((r) => r.includes("FAIL")).length} failing)`);
